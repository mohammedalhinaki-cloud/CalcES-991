import type { MathfieldElement } from 'mathlive'
import type { Page } from '@playwright/test'
async function mode(page:Page,name:string){
 await page.locator('[data-key="mode"]').click()
 await page.getByRole('dialog').getByRole('button',{name:new RegExp(name)}).click()
}
async function formula(page:Page,latex:string){
 await page.locator('math-field').evaluate((el,value)=>{const f=el as MathfieldElement;f.value=value;f.dispatchEvent(new InputEvent('input',{bubbles:true}))},latex)
}
