test('preview, invalid expressions, repeated equals, and history recall do not inflate the counter',async({page})=>{
 await page.goto('/');await page.evaluate(()=>{localStorage.clear();localStorage.setItem('rate_done','1')})
 const field=page.locator('math-field')
 const formula=async(value:string)=>field.evaluate((el,value)=>{const f=el as MathfieldElement;f.value=value;f.dispatchEvent(new InputEvent('input',{bubbles:true}))},value)
 await formula('2+3');await expect(page.getByLabel('النتيجة',{exact:true})).toHaveText('5')
 expect(await page.evaluate(()=>localStorage.getItem('calc_count'))).toBeNull()
 await formula('1/0');await page.locator('[data-key="equals"]').click()
 expect(await page.evaluate(()=>localStorage.getItem('calc_count'))).toBeNull()
 await formula('2+3');await page.locator('[data-key="equals"]').click();await page.locator('[data-key="equals"]').click()
 expect(await page.evaluate(()=>localStorage.getItem('calc_count'))).toBe('1')
 await page.getByRole('button',{name:'السجل (1)',exact:true}).click();await page.getByRole('button',{name:'استدعاء 5',exact:true}).click()
 expect(await page.evaluate(()=>localStorage.getItem('calc_count'))).toBe('1')
})
