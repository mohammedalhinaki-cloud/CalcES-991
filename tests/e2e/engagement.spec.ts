import {test,expect} from './fixtures'
import type {MathfieldElement} from 'mathlive'
test.use({hasTouch:true,viewport:{width:390,height:844}})
async function calculate(page:import('@playwright/test').Page,value:number){
 await page.getByRole('button',{name:'AC',exact:true}).click()
 await page.getByRole('button',{name:String(value),exact:true}).click()
 await page.getByRole('button',{name:'=',exact:true}).click()
}
test('counts committed results only and permanently dismisses the fifth-operation prompt',async({page})=>{
 await page.goto('/');await page.evaluate(()=>localStorage.clear())
 for(let i=1;i<=4;i++)await calculate(page,i)
 await expect(page.getByRole('dialog',{name:'رأيك يصنع الفارق! ⭐️'})).not.toBeVisible()
 await calculate(page,5)
 const prompt=page.getByRole('dialog',{name:'رأيك يصنع الفارق! ⭐️'})
 await expect(prompt).toBeVisible()
 await expect.poll(()=>page.evaluate(()=>localStorage.getItem('calc_count'))).toBe('5')
 await prompt.getByRole('button',{name:'إغلاق ✖️'}).click()
 await calculate(page,6)
 await expect(prompt).not.toBeVisible()
 expect(await page.evaluate(()=>localStorage.getItem('rate_done'))).toBe('1')
 await expect(page.getByLabel('النتيجة')).toContainText('6')
})
test('defers the prompt while history is open and remembers later for three days',async({page})=>{
 await page.setViewportSize({width:360,height:640});await page.goto('/')
 await page.evaluate(()=>localStorage.clear())
 await page.getByRole('button',{name:/السجل \(/}).click()
 await page.evaluate(()=>{localStorage.setItem('calc_count','5');window.dispatchEvent(new Event('calces:calculation'))})
 const prompt=page.getByRole('dialog',{name:'رأيك يصنع الفارق! ⭐️'})
 await expect(prompt).not.toBeVisible()
 await page.getByRole('dialog').getByRole('button',{name:'إغلاق',exact:true}).click()
 await expect(prompt).toBeVisible()
 const bounds=await prompt.boundingBox();expect(bounds!.y).toBeGreaterThanOrEqual(0);expect(bounds!.y+bounds!.height).toBeLessThanOrEqual(640)
 await prompt.getByRole('button',{name:'ذكرني لاحقاً ⏰'}).click()
 const remaining=await page.evaluate(()=>Number(localStorage.getItem('rate_remind_at'))-Date.now())
 expect(remaining).toBeGreaterThan(3*86400000-10000)
 await calculate(page,7);await expect(prompt).not.toBeVisible()
})
