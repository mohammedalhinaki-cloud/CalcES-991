test('share uses the native sheet and cancelling it does not copy the link',async({page})=>{
 await page.addInitScript(()=>{
  Object.defineProperty(navigator,'share',{configurable:true,value:async(data:ShareData)=>{document.documentElement.dataset.sharedUrl=data.url;throw new DOMException('cancelled','AbortError')}})
  Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{document.documentElement.dataset.copied='yes'}}})
 })
 await page.goto('/');await expect(page.locator('math-field')).toBeVisible()
 await page.getByRole('button',{name:'مشاركة الحاسبة'}).click()
 await expect(page.locator('html')).toHaveAttribute('data-shared-url','http://127.0.0.1:5174/')
 await expect(page.locator('html')).not.toHaveAttribute('data-copied','yes')
})
