test('install consumes the browser prompt and responds to installed state',async({page})=>{
 await page.addInitScript(()=>window.addEventListener('beforeinstallprompt',event=>{if(event.isTrusted){event.preventDefault();event.stopImmediatePropagation()}},true))
 await page.goto('/');await expect(page.locator('math-field')).toBeVisible()
 const intercepted=await page.evaluate(()=>{
  const event=new Event('beforeinstallprompt',{cancelable:true})
  Object.assign(event,{prompt:async()=>{document.documentElement.dataset.installCalls=String(Number(document.documentElement.dataset.installCalls??0)+1)},userChoice:Promise.resolve({outcome:'accepted'})})
  window.dispatchEvent(event);return event.defaultPrevented
 })
 expect(intercepted).toBe(true)
 await page.getByRole('button',{name:'تثبيت التطبيق'}).click()
 await expect(page.locator('html')).toHaveAttribute('data-install-calls','1')
 await page.evaluate(()=>window.dispatchEvent(new Event('appinstalled')))
 await expect(page.getByRole('button',{name:'التطبيق مثبت'})).toBeVisible()
 await page.getByRole('button',{name:'التطبيق مثبت'}).click()
 await expect(page.locator('html')).toHaveAttribute('data-install-calls','1')
})
test('production precaches the calculator and worker for an offline installed launch',async({page,context},testInfo)=>{
 test.skip(!testInfo.config.metadata.production,'Production service worker only')
 await page.goto('/');await expect(page.locator('math-field')).toBeVisible()
 const manifest=await (await page.request.get('/manifest.webmanifest')).json()
 expect(manifest.display).toBe('standalone')
 expect(manifest.icons.map((icon:{sizes:string})=>icon.sizes)).toEqual(['192x192','512x512'])
 await page.evaluate(async()=>{await navigator.serviceWorker.ready;if(!navigator.serviceWorker.controller)await new Promise<void>(resolve=>navigator.serviceWorker.addEventListener('controllerchange',()=>resolve(),{once:true}))})
 const cdp=await context.newCDPSession(page)
 const installability=await cdp.send('Page.getInstallabilityErrors')
 // Playwright's isolated context is incognito; that is not a manifest defect.
 expect(installability.installabilityErrors.filter((error:{errorId:string})=>error.errorId!=='in-incognito')).toEqual([])
 await cdp.detach()
 await context.setOffline(true)
 try{
  await page.reload();await expect(page.locator('math-field')).toBeVisible()
  await page.locator('math-field').evaluate(el=>{const field=el as MathfieldElement;field.value='x^2';field.dispatchEvent(new InputEvent('input',{bubbles:true}))})
  await page.locator('[data-key="integral"]').click();await page.locator('[data-key="equals"]').click()
  await expect(page.getByLabel('النتيجة',{exact:true})).toHaveText('0.33333333333333',{timeout:15000})
 }finally{await context.setOffline(false)}
})
