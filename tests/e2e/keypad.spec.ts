import { expect, test } from './fixtures'
import type { MathfieldElement } from 'mathlive'

test('keypad edits at cursor, deletes selections and recalls the committed answer',async({page})=>{
  await page.goto('/')
  const field=page.locator('math-field')
  await expect(field).toBeVisible()
  const press=async(...ids:string[])=>{for(const id of ids)await page.locator(`[data-key="${id}"]`).click()}
  await press('1','2','3')
  await page.getByRole('button',{name:'المؤشر ◀',exact:true}).click()
  await press('9')
  await expect(page.getByLabel('النتيجة',{exact:true})).toHaveText('1293')
  await press('delete','equals','clear','answer')
  await expect(page.getByLabel('النتيجة',{exact:true})).toHaveText('123')
  await field.evaluate(el=>{const f=el as MathfieldElement;f.selection={ranges:[[0,f.lastOffset]]}})
  await press('delete')
  await expect(page.getByLabel('النتيجة',{exact:true})).toHaveText('—')
})

test('SHIFT/ALPHA change button labels, highlight and consume after insertion',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('console',m=>{if(['warning','error'].includes(m.type()))errors.push(m.text())})
  await page.goto('/')
  await expect(page.locator('math-field')).toBeVisible()
  const shift=page.locator('[data-key="shift"]')
  await shift.click()
  await expect(shift).toHaveAttribute('aria-pressed','true')
  await expect(page.locator('[data-key="sqrt"]')).toHaveAttribute('aria-label','∛')
  await expect(page.locator('[data-key="sqrt"]')).toHaveText('√')
  await expect(page.locator('[data-key="sqrt"]')).toHaveAttribute('data-secondary-active','true')
  await page.locator('[data-key="sqrt"]').click()
  expect(await page.locator('math-field').evaluate(el=>(el as MathfieldElement).getValue())).toContain('\\sqrt[3]')
  await expect(shift).toHaveAttribute('aria-pressed','false')
  await page.locator('[data-key="clear"]').click()
  await page.locator('[data-key="alpha"]').click()
  await expect(page.locator('[data-key="sin"]')).toHaveAttribute('aria-label','D')
  await expect(page.locator('[data-key="sin"]')).toHaveText('sin')
  await page.locator('[data-key="sin"]').click()
  expect(await page.locator('math-field').evaluate(el=>(el as MathfieldElement).getValue())).toBe('D')
  await expect(page.locator('[data-key="alpha"]')).toHaveAttribute('aria-pressed','false')
  await page.waitForLoadState('networkidle')
  expect(errors).toEqual([])
})

test('mode menus preserve the field, switch key functions and gate base digits',async({page})=>{
  await page.goto('/')
  const field=page.locator('math-field')
  await expect(field).toBeVisible()
  await page.locator('[data-key="1"]').click()
  await field.evaluate(el=>{(el as HTMLElement).dataset.identity='persistent'})
  const mode=async(name:string)=>{
    await page.locator('[data-key="mode"]').click()
    await page.getByRole('dialog').getByRole('button',{name:new RegExp(name)}).click()
  }
  await mode('MATRIX')
  await expect(page.locator('[data-key="integral"]')).toHaveText('det')
  expect(await field.evaluate(el=>(el as HTMLElement).dataset.identity)).toBe('persistent')
  expect(await field.evaluate(el=>(el as MathfieldElement).getValue())).toBe('1')
  await mode('STAT')
  await expect(page.locator('[data-key="integral"]')).toHaveText('x̄')
  await mode('CMPLX')
  await expect(page.locator('[data-key="logbase"]')).toHaveText('i')
  await mode('EQUATION')
  await expect(page.locator('[data-key="calc"]')).toHaveText('f(x)=0')
  await mode('BASE-N')
  await page.locator('[data-key="logbase"]').click()
  await expect(page.locator('[data-key="2"]')).toBeDisabled()
  await expect(page.locator('[data-key="1"]')).toBeEnabled()
  await expect(page.locator('[data-key="sin"]')).toHaveText('AND')
  await mode('COMP')
  await expect(page.locator('[data-key="2"]')).toBeEnabled()
  await expect(page.getByLabel('النتيجة',{exact:true})).toHaveText('1')
})

test('setup, AC, power and touch keypad preserve normal interaction',async({browser})=>{
  const context=await browser.newContext({hasTouch:true,isMobile:true,viewport:{width:390,height:844}})
  await context.addInitScript(()=>localStorage.setItem('calces_language','ar'))
 const page=await context.newPage()
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('console',m=>{if(['warning','error'].includes(m.type()))errors.push(m.text())})
  await page.goto('http://127.0.0.1:5174/')
  await expect(page.locator('math-field')).toBeVisible()
  for(const id of ['2','+','3','equals'])await page.locator(`[data-key="${id}"]`).tap()
  await expect(page.getByLabel('النتيجة',{exact:true})).toHaveText('5')
  await page.locator('[data-key="shift"]').tap()
  await page.locator('[data-key="mode"]').tap()
  await page.getByRole('button',{name:'RAD',exact:true}).tap()
  await expect(page.getByLabel('مؤشرات الحاسبة')).toContainText('RAD')
  await page.locator('[data-key="shift"]').tap()
  await page.locator('[data-key="clear"]').tap()
  await expect(page.locator('[data-key="1"]')).toBeDisabled()
  await page.locator('[data-key="on"]').tap()
  await expect(page.locator('[data-key="1"]')).toBeEnabled()
  await page.locator('[data-key="clear"]').tap()
  await expect(page.getByLabel('النتيجة',{exact:true})).toHaveText('—')
  await page.waitForLoadState('networkidle')
  expect(errors).toEqual([])
  await context.close()
})
